// updateSPAPeriods regenerates the period and upload-folder table the
// Evidence SPA checks its own period and path code against:
//
//	go test ./internal/planner/ -run TestSPAGoldenPeriods -update
//
// then copy testdata/spa-golden/periods.json byte-for-byte to the SPA
// (see testdata/spa-golden/README.md).
var updateSPAPeriods = flag.Bool("update", false, "regenerate testdata/spa-golden/periods.json")

const spaPeriodsGolden = "testdata/spa-golden/periods.json"

const spaNewYear2027 = "2027-01-01T00:00:00Z"

// spaInstants are UTC instants chosen at period edges: year, quarter and
// month boundaries, ISO weeks that belong to another year, and a leap day.
var spaInstants = []string{
	"2025-12-31T23:59:59Z",
	"2026-01-01T00:00:00Z",
	"2026-02-15T12:00:00Z",
	"2026-03-31T23:59:59Z",
	"2026-04-01T00:00:00Z",
	"2026-06-30T12:00:00Z",
	"2026-09-30T23:59:59Z",
	"2026-12-28T08:00:00Z", // ISO 2026-W53
	spaNewYear2027,         // still ISO 2026-W53
	"2027-01-04T00:00:00Z", // ISO 2027-W01
	"2021-01-03T23:59:59Z", // ISO 2020-W53
	"2024-02-29T12:00:00Z", // leap day
}

// spaFolderCases pin manual.FolderPrefix's prefix normalization.
var spaFolderCases = []struct{ prefix, evidenceID, periodID string }{
	{"manual/", catalogAccessReview, period2026Q1},
	{"manual", catalogAccessReview, period2026Q1},
	{"manual//", catalogAccessReview, period2026Q1},
	{"", "risk_assessment", "2026"},
	{"evidence/manual/", "vendor_assurance.acme_cloud", "2026"},
	{"evidence/manual/", "change_review", "2026-W01"},
}

type spaPeriodRow struct {
	Instant     string `json:"instant"`
	Cadence     string `json:"cadence"`
	InCatalog   bool   `json:"used_by_catalog"`
	Frequency   string `json:"frequency"`
	PeriodID    string `json:"period_id"`
	PeriodStart string `json:"period_start"`
	PeriodEnd   string `json:"period_end"`
	Folder      string `json:"folder"`
}

type spaFolderRow struct {
	Prefix     string `json:"prefix"`
	EvidenceID string `json:"evidence_id"`
	PeriodID   string `json:"period_id"`
	Folder     string `json:"folder"`
}

type spaPeriodsFile struct {
	Comment    string         `json:"comment"`
	Prefix     string         `json:"prefix"`
	EvidenceID string         `json:"evidence_id"`
	Periods    []spaPeriodRow `json:"periods"`
	Folders    []spaFolderRow `json:"folders"`
}

// spaCadences returns every cadence a shipped manual catalog uses, plus
// the calendar cadences the SPA can derive a period for, mapped to
// whether a catalog uses them today.
func spaCadences(t *testing.T) map[string]bool {
	t.Helper()
	used := map[string]bool{}
	for _, id := range frameworks.IDs() {
		f, ok := frameworks.Lookup(id)
		if !ok || f.ManualCatalog == nil {
			continue
		}
		for _, e := range f.ManualCatalog() {
			used[e.Cadence] = true
		}
	}
	if len(used) == 0 {
		t.Fatal("no manual catalog cadences found")
	}
	for _, c := range []string{"daily", "weekly", "monthly", cadenceQuarterly, cadenceAnnual} {
		if !used[c] {
			used[c] = false
		}
	}
	return used
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func buildSPAPeriods(t *testing.T) spaPeriodsFile {
	t.Helper()
	const prefix, evidenceID = "manual/", "example_entry"
	// The default period config, which is what the SPA assumes: calendar
	// quarters, calendar years.
	cfg := &spec.PeriodConfig{}
	out := spaPeriodsFile{
		Comment: "Generated by TestSPAGoldenPeriods in sigcomply-cli internal/planner. " +
			"Do not edit; regenerate with -update and copy to the Evidence SPA.",
		Prefix:     prefix,
		EvidenceID: evidenceID,
	}
	for _, raw := range spaInstants {
		at, err := time.Parse(time.RFC3339, raw)
		if err != nil {
			t.Fatal(err)
		}
		cadences := spaCadences(t)
		for _, cadence := range sortedKeys(cadences) {
			p, err := planner.CadencePeriod(cfg, at, cadence)
			if err != nil {
				t.Fatalf("CadencePeriod(%s, %s): %v", raw, cadence, err)
			}
			out.Periods = append(out.Periods, spaPeriodRow{
				Instant:     raw,
				Cadence:     cadence,
				InCatalog:   cadences[cadence],
				Frequency:   string(manualcatalog.FrequencyFromCadence(cadence)),
				PeriodID:    p.ID,
				PeriodStart: p.Start.UTC().Format(time.RFC3339Nano),
				PeriodEnd:   p.End.UTC().Format(time.RFC3339Nano),
				Folder:      manual.FolderPrefix(prefix, evidenceID, p.ID),
			})
		}
	}
	for _, c := range spaFolderCases {
		out.Folders = append(out.Folders, spaFolderRow{
			Prefix: c.prefix, EvidenceID: c.evidenceID, PeriodID: c.periodID,
			Folder: manual.FolderPrefix(c.prefix, c.evidenceID, c.periodID),
		})
	}
	return out
}

func TestSPAGoldenPeriods(t *testing.T) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	if err := enc.Encode(buildSPAPeriods(t)); err != nil {
		t.Fatal(err)
	}
	if *updateSPAPeriods {
		if err := os.MkdirAll(filepath.Dir(spaPeriodsGolden), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(spaPeriodsGolden, buf.Bytes(), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(spaPeriodsGolden)
	if err != nil {
		t.Fatalf("%v (generate with -update)", err)
	}
	if !bytes.Equal(got, buf.Bytes()) {
		t.Errorf("%s is stale; rerun with -update and copy it to the Evidence SPA", spaPeriodsGolden)
	}
}
